#!/usr/bin/env node
/**
 * The three screenshot device lists have to agree (IOS-AUDIT-REL-008 AC2).
 *
 * WHY. ios/fastlane/Snapfile already carried the sentence "These must match the
 * Fastfile screenshots lane and the ios-screenshots.yml GitHub Actions
 * workflow" - a rule stated in a comment and enforced by nothing. The lane is
 * workflow_dispatch-only, so a drift between the three produces no failure and
 * no signal; the first symptom is a submission missing a required size, months
 * later.
 *
 * The lists live in three different languages - Ruby, Ruby DSL and Bash inside
 * YAML - which is exactly why nobody keeps them in step by hand:
 *
 *   ios/fastlane/Snapfile                    devices([...])
 *   ios/fastlane/Fastfile                    devices: [...]
 *   .github/workflows/ios-screenshots.yml    DEVICES=( ... )   (twice)
 *
 * SECOND ASSERTION: every committed screenshot in app-store-screenshots/ has to
 * come from a device this lane can actually produce. Sixteen of them were
 * generated by hand from Pro Max simulators the lane did not list, under a
 * comment claiming App Store Connect rejects Pro Max dimensions. Assets and
 * generator disagreeing is the defect this check exists to catch.
 *
 * NOT A SIZE VALIDATOR. It does not know which sizes App Store Connect requires
 * this quarter and does not pretend to - that is a submission decision. It only
 * asserts the repo agrees with itself.
 *
 * Usage: node scripts/check-screenshot-devices.mjs
 */

import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SNAPFILE = join(ROOT, 'ios/fastlane/Snapfile');
const FASTFILE = join(ROOT, 'ios/fastlane/Fastfile');
const WORKFLOW = join(ROOT, '.github/workflows/ios-screenshots.yml');
const SHOTS = join(ROOT, 'app-store-screenshots');

const failures = [];

/** Quoted strings inside the first block matching `pattern`. */
function namesIn(text, pattern, label) {
  const match = text.match(pattern);
  if (!match) {
    failures.push(`Could not find the ${label} device list. If it moved, update this check.`);
    return null;
  }
  return (match[1].match(/"([^"]+)"/g) ?? []).map((s) => s.slice(1, -1));
}

function readOrFail(path, label) {
  if (!existsSync(path)) {
    failures.push(`${label} not found at ${path} - refusing to pass.`);
    return null;
  }
  return readFileSync(path, 'utf8');
}

const snapText = readOrFail(SNAPFILE, 'Snapfile');
const fastText = readOrFail(FASTFILE, 'Fastfile');
const wfText = readOrFail(WORKFLOW, 'screenshot workflow');

const snap = snapText && namesIn(snapText, /devices\(\[([\s\S]*?)\]\)/, 'Snapfile');
const fast = fastText && namesIn(fastText, /devices:\s*\[([\s\S]*?)\]/, 'Fastfile');

// The workflow declares the same array twice - simulator creation and
// pre-booting. Both are checked, because one being updated alone is precisely
// the drift this catches.
// Terminated by a `)` at the start of a line, not the first `)` anywhere -
// "iPad Pro 13-inch (M4)" contains one and a lazy match stops inside it.
const wfBlocks = wfText ? [...wfText.matchAll(/DEVICES=\(([\s\S]*?)\n\s*\)/g)] : [];
if (wfText && wfBlocks.length === 0) {
  failures.push('Could not find any DEVICES=( ... ) array in the screenshot workflow.');
}
const wfLists = wfBlocks.map((m) => (m[1].match(/"([^"]+)"/g) ?? []).map((s) => s.slice(1, -1)));

const lists = [
  ['Snapfile', snap],
  ['Fastfile', fast],
  ...wfLists.map((l, i) => [`ios-screenshots.yml DEVICES[${i + 1}]`, l]),
].filter(([, l]) => Array.isArray(l));

if (lists.length >= 2) {
  const [refName, ref] = lists[0];
  const key = (l) => [...l].sort().join(' | ');
  for (const [name, list] of lists.slice(1)) {
    if (key(list) !== key(ref)) {
      const missing = ref.filter((d) => !list.includes(d));
      const extra = list.filter((d) => !ref.includes(d));
      failures.push(
        `${name} does not match ${refName}.` +
          (missing.length ? ` Missing: ${missing.join(', ')}.` : '') +
          (extra.length ? ` Unexpected: ${extra.join(', ')}.` : '')
      );
    }
  }
}

// --- Committed assets must name a device the lane can produce ---------------
const known = new Set(lists.flatMap(([, l]) => l));
if (existsSync(SHOTS) && known.size > 0) {
  const files = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, entry.name);
      if (entry.isDirectory()) walk(p);
      else if (/\.(png|jpg|jpeg)$/i.test(entry.name)) files.push(p);
    }
  };
  walk(SHOTS);

  // Fastlane names files "<Device>-<screen>.png".
  const unknown = new Set();
  for (const file of files) {
    const device = basename(file).split('-')[0].trim();
    if (device && !known.has(device)) unknown.add(device);
  }
  if (unknown.size > 0) {
    failures.push(
      `app-store-screenshots/ contains assets from device(s) the lane does not generate: ` +
        `${[...unknown].join(', ')}. Either add them to the three device lists, or the ` +
        `assets were produced by hand and nothing reproduces them.`
    );
  }
  console.log(`[screenshot-devices] ${files.length} committed asset(s) across ${known.size} known device(s).`);
}

console.log(`[screenshot-devices] ${lists.length} device list(s) compared.`);

if (failures.length > 0) {
  console.error(`\nX ${failures.length} screenshot-device failure(s):`);
  for (const f of failures) console.error(`  - ${f}`);
  console.error('\n  See IOS-AUDIT-REL-008.\n');
  process.exit(1);
}

console.log('\nOK Snapfile, Fastfile and the workflow name the same devices.');
